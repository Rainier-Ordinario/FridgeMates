/**
 * Bundles only the Fluent Emoji Flat icons we use into assets/icons/fluent.generated.ts,
 * so the app renders them offline with react-native-svg. Run: node scripts/build-food-icons.mjs
 * Icons: Microsoft Fluent Emoji (MIT), via @iconify-json/fluent-emoji-flat.
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { ICON_NAMES } from './icon-names.mjs';

const require = createRequire(import.meta.url);
const data = require('@iconify-json/fluent-emoji-flat/icons.json');
const w = data.width ?? 32;
const h = data.height ?? 32;

const missing = ICON_NAMES.filter((n) => !data.icons[n]);
if (missing.length) {
  console.error('Missing icons:', missing.join(', '));
  process.exit(1);
}

const entries = ICON_NAMES.map((n) => {
  const icon = data.icons[n];
  const iw = icon.width ?? w;
  const ih = icon.height ?? h;
  return `  '${n}': { w: ${iw}, h: ${ih}, body: ${JSON.stringify(icon.body)} },`;
});

const out = `// GENERATED by scripts/build-food-icons.mjs. Do not edit by hand.
// Microsoft Fluent Emoji (flat), MIT License: https://github.com/microsoft/fluentui-emoji
export type FluentIconName = ${ICON_NAMES.map((n) => `'${n}'`).join(' | ')};

export const fluentIcons: Record<FluentIconName, { w: number; h: number; body: string }> = {
${entries.join('\n')}
};
`;
writeFileSync(new URL('../assets/icons/fluent.generated.ts', import.meta.url), out);
console.log(`wrote ${ICON_NAMES.length} icons`);
